/*Un método es un bloque de código reutilizable 
dentro de una clase que ejecuta una tarea específica al ser invocado. */

typeof 'hola'; // 'string'
typeof new String('hola'); // 'object' ← no lo hagas
'hola' === 'hola'; // true
new String('hola') === new String('hola'); // false (son dos objetos distintos)